def lookup(a, b):
    m, k = a.shape
    return GEOMETRY.get(
        (
            m,
            b.shape[1],
            k,
            *a.stride(),
            *b.stride(),
            a.storage_offset(),
            b.storage_offset(),
        )
    )


def launch(a, b, out, recipe):
    m, k = a.shape
    n = b.shape[1]
    matmul[(triton.cdiv(m, 32), triton.cdiv(n, 32))](
        a,
        b,
        out,
        m,
        n,
        k,
        *a.stride(),
        *b.stride(),
        TILE=4,
        W=2,
        DEPTH=2,
        num_warps=2,
        enable_fp_fusion=False,
    )
    fix_edges(a, b, out, recipe)


def fix_edges(a, b, out, recipe, waves=4, step=16):
    m, k = a.shape
    n = b.shape[1]
    rows, gaps, edges, segments, mode = recipe
    if gaps:
        width = sum(count for _, count in gaps)
        columns[(triton.cdiv(m * width, 64 * waves),)](
            a,
            b,
            out,
            m,
            n,
            k,
            *a.stride(),
            *b.stride(),
            GAPS=gaps,
            ROWS=rows,
            WIDTH=width,
            W=waves,
            STEP=step,
            MODE=mode,
            num_warps=waves,
            enable_fp_fusion=False,
        )
    for edge, height in edges:
        for col, width in segments:
            gemv[(triton.cdiv(width, 8), height)](
                b,
                a,
                out,
                width,
                k,
                b.stride(1),
                b.stride(0),
                a.stride(1),
                A_OFFSET=b.storage_offset() + col * b.stride(1),
                B_OFFSET=a.storage_offset() + edge * a.stride(0),
                BO=8,
                STEPS=16,
                A_START=col * b.stride(1),
                B_START=edge * a.stride(0),
                C_START=edge * n + col,
                B_BATCH_STRIDE=a.stride(0),
                C_BATCH_STRIDE=n,
                num_warps=1,
                enable_fp_fusion=False,
            )


